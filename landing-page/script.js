const storageKey = "ruby-kiwi-language";
const translatableNodes = document.querySelectorAll("[data-i18n]");
const toggleButtons = document.querySelectorAll("[data-lang-toggle]");

function applyLanguage(lang) {
  const locale = translations[lang] ? lang : "ko";

  document.documentElement.lang = locale;

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    const value = translations[locale][key];

    if (!value) {
      return;
    }

    const targetAttribute = node.dataset.i18nAttr;

    if (targetAttribute) {
      node.setAttribute(targetAttribute, value);
      return;
    }

    node.textContent = value;
  });

  toggleButtons.forEach((button) => {
    const isActive = button.dataset.langToggle === locale;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  window.localStorage.setItem(storageKey, locale);
}

function getInitialLanguage() {
  const savedLanguage = window.localStorage.getItem(storageKey);

  if (savedLanguage && translations[savedLanguage]) {
    return savedLanguage;
  }

  return navigator.language.toLowerCase().startsWith("ko") ? "ko" : "en";
}

toggleButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.langToggle);
  });
});

applyLanguage(getInitialLanguage());
